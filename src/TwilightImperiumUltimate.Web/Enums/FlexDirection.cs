namespace TwilightImperiumUltimate.Web.Enums;

/// <summary>
/// Flex direction for flex containers.
/// </summary>
public enum FlexDirection
{
    /// <summary>
    /// Row direction (default); items flow left to right.
    /// </summary>
    Row,

    /// <summary>
    /// Column direction; items flow top to bottom.
    /// </summary>
    Column,

    /// <summary>
    /// Row reverse direction; items flow right to left.
    /// </summary>
    RowReverse,

    /// <summary>
    /// Column reverse direction; items flow bottom to top.
    /// </summary>
    ColumnReverse,
}
