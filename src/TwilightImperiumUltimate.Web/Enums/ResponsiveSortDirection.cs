namespace TwilightImperiumUltimate.Web.Enums;

/// <summary>
/// The current sort state of a <c>ResponsiveDataGrid</c> column.
/// </summary>
public enum ResponsiveSortDirection
{
    /// <summary>
    /// The column is not the current sort column.
    /// </summary>
    None,

    /// <summary>
    /// Sorted ascending.
    /// </summary>
    Ascending,

    /// <summary>
    /// Sorted descending.
    /// </summary>
    Descending,
}
